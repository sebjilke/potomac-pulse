// Mechanical generator for the backtest copies of production text (plan section 1 and section 4).
// Writes rising_limb_model_variants.mjs and rising_limb_learning_gate.mjs. Never edit those by hand; rerun this.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { HERE, PROD_PATH, ANCHORS, readLines, sha256, extractModel, extractGate, blobSha1, fingerprints } from './drift_lib.mjs';

export function generate({ prodPath = PROD_PATH, outDir = HERE, write = true } = {}) {
  const lines = readLines(prodPath);
  const m = extractModel(lines);
  const g = extractGate(lines);
  const blob = blobSha1(prodPath);   // header line 2 only; tests compare the files without that line
  const startsWith = (l, a) => l.trim().startsWith(a);

  // ---- model copy with the four VARIANT-HOOK lines ----
  const hooked = [];
  for (const l of m.model) {
    if (startsWith(l, ANCHORS.R)) {
      hooked.push(l);
      hooked.push("const rising = !!(porRiseRate && porRiseRate.flowState === 'rising' && porRiseRate.ratePerHour > 0); // VARIANT-HOOK[R]");
    } else if (startsWith(l, ANCHORS.H1)) {
      hooked.push('let mult = getFlowMultiplier(useB && rising ? Math.max(lf.q, por.q) : lf.q); // VARIANT-HOOK[H1]');
    } else if (startsWith(l, ANCHORS.H2)) {
      hooked.push('const historicMult = getFlowMultiplier(useB && rising ? Math.max(historicPoR.cfs, por.q) : historicPoR.cfs); // VARIANT-HOOK[H2]');
    } else if (startsWith(l, ANCHORS.H3)) {
      hooked.push('porEstimateCFS = useA ? Math.round(historicPoR.cfs * appliedRatio) + monocacyFlow + gooseFlow + broadRunFlow + senecaFlow : Math.round(porEstimateCFS * appliedRatio); // VARIANT-HOOK[H3]');
    } else hooked.push(l);
  }
  const variants = [
    '// GENERATED by generate_copies.mjs from netlify/functions/scheduled-update.js. DO NOT EDIT.',
    `// source blob ${blob} (git hash-object of scheduled-update.js; informational, ignored by the drift tests)`,
    `// MODEL block sha256 ${sha256(m.model.join('\n'))}; POR block sha256 ${sha256(m.por.join('\n'))}`,
    "import { createRequire } from 'node:module';",
    'const require = createRequire(import.meta.url);',
    "const M = require('../../netlify/functions/shared/model.js');",
    'const { getFlowMultiplier, getFlowState, getPoRtoGFTravelTime, getGFtoLFTravelTime, selectHistoricReading,',
    '  getPoRRiseRateFromHistory, CEILING_RATIO, DECAY_CAP, TRIB_FALLBACK, estimateLFStage, applyGFCorrection, EF_MODEL, getEFWeight } = M;',
    '',
    '// variant in {base, A, B, C}. The copied text sits at column 0 inside the factory so it stays line-for-line comparable.',
    'export function makeVariant(variant) {',
    "if (!['base','A','B','C'].includes(variant)) throw new Error('bad variant ' + variant);",
    "const useA = variant === 'A' || variant === 'C';",
    "const useB = variant === 'B' || variant === 'C';",
    '// POR-COPY-BEGIN',
    ...m.por,
    '// POR-COPY-END',
    '// MODEL-COPY-BEGIN',
    ...hooked,
    '// MODEL-COPY-END',
    'return makeGFPrediction;',
    '}',
    '',
  ].join('\n');

  // ---- learning gate copy ----
  const blk = [];
  for (let i = 0; i < g.block.length; i++) {
    if (i === g.claim[0]) blk.push("const { data: claimed, error: claimErr } = hooks.claim(pred); // GATE-HOOK[claim]");
    if (i === g.bin[0]) blk.push('const { data: existingBin, error: binReadErr } = hooks.binRead(binKey); // GATE-HOOK[binread]');
    if ((i >= g.claim[0] && i <= g.claim[1]) || (i >= g.bin[0] && i <= g.bin[1])) continue;
    blk.push(g.block[i]);
  }
  const gate = [
    '// GENERATED by generate_copies.mjs from netlify/functions/scheduled-update.js (validatePendingPredictions). DO NOT EDIT.',
    `// source blob ${blob} (git hash-object of scheduled-update.js; informational, ignored by the drift tests)`,
    `// GATE block sha256 ${sha256(g.block.join('\n'))}; PREAMBLE sha256 ${sha256(g.pre.join('\n'))}`,
    "import { createRequire } from 'node:module';",
    'const require = createRequire(import.meta.url);',
    "const { EF_MODEL, estimateLFFlowFromStage, isIcePlausible, classifyOutlier, updateCorrectionBin } = require('../../netlify/functions/shared/model.js');",
    "const { binStatsOf } = require('../../netlify/functions/scheduled-update.js')._test;  // pure helper, production text",
    '// Side-effect calls inside the block run against these no-ops (plan section 4).',
    'const insertObs = async () => ({ error: null });',
    'const logValidationFate = async () => {};',
    'const logMsg = (x) => (x == null ? null : String(x));',
    '',
    '// Runs the ported production block for ONE claimed-or-claimable due pending. `continue` in the block leaves the one-pass loop.',
    'export async function runLearningGate({ pred, lf, ef, waterTempC, now, delayMinutes, hooks, client = {}, logCtx = {} }) {',
    'let captured = null;',
    'for (const __once of [0]) {',
    '// PREAMBLE-COPY-BEGIN',
    ...g.pre,
    '// PREAMBLE-COPY-END',
    '// GATE-COPY-BEGIN',
    ...blk,
    '// GATE-COPY-END',
    'captured = binUpdate;',
    '}',
    'return { isHardFlagged, isSoftFlagged, errorCFS, flowBin, flowState, binKey, binData, binReadFailed, binUpdate: captured, anomalyFlags, actualCFS, rawCFS };',
    '}',
    'return { claimLost: true };',
    '}',
    '',
  ].join('\n');

  if (write) {
    fs.writeFileSync(path.join(outDir, 'rising_limb_model_variants.mjs'), variants);
    fs.writeFileSync(path.join(outDir, 'rising_limb_learning_gate.mjs'), gate);
  }
  const fp = JSON.stringify(fingerprints(lines), null, 1) + '\n';
  if (write) fs.writeFileSync(path.join(outDir, 'production_fingerprints.json'), fp);
  return { variants, gate, blob, fp };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);
if (isMain) { const r = generate(); console.log('generated from blob', r.blob); }
