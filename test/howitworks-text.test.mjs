// v39.4 (A9): the How It Works page, Tech Appendix and README no longer carry the statements the
// October 2026 flood contradicted. Text under test is the page text itself.
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');
const html = read('index.html');
const appendix = read('src/assets/tech-appendix.md');
const readme = read('README.md');

describe('old statements are gone', () => {
    it('index.html', () => {
        for (const old of ['plan around it', 'improves continuously', 'Every hour, the server checks', 'could shift 10&ndash;20%', 'ballpark only', 'upper limit', 'what the model itself estimated']) {
            assert.ok(!html.includes(old), old);
        }
    });
    it('tech appendix', () => {
        for (const old of ['improves continuously', 'every hour a pending prediction', 'Make new prediction and store for future validation']) assert.ok(!appendix.includes(old), old);
    });
    it('README', () => assert.ok(!readme.includes('Validation**: Server-only, every hour')));
});

describe('replacement text is present', () => {
    it('index.html', () => {
        for (const s of [
            'which can be over an hour old. Rain that falls between Point of Rocks and Great Falls can push the real flow above the capped number.',
            "shows the model's own value.",
            'The model learns from most checks, even when no one is looking at the site, but it can lag a fast-changing river.',
            'The server checks one earlier prediction at a time against what Little Falls actually recorded',
            'so most hourly predictions are never scored.',
            'It mostly reflects how complete the inputs are (tributary gauges reporting, upstream timing, Edwards Ferry agreeing). It also drops when the latest check against Little Falls was far off. It is not a measured error rate.',
            'the typical (median) miss was about 9% at every level, and a few High readings were off by more than 25%.'
        ]) assert.ok(html.includes(s), s);
    });
    it('tech appendix keeps the true hourly line and fixes the false ones', () => {
        assert.ok(appendix.includes('A serverless function executes every hour:'));
        assert.ok(appendix.includes('6. Make a new prediction; store it only if no earlier prediction is still waiting to be checked'));
        assert.ok(appendix.includes('The model learns from most checks, even when no browsers are open, but it can lag a fast-changing river.'));
        assert.ok(appendix.includes('whenever the single pending prediction'));
    });
    it('appendix confidence section matches the legend', () => assert.ok(appendix.includes('It is not a measured error rate.') && appendix.includes('it also drops when the latest check against Little Falls was far off')));
    it('README hourly line carries the pending condition', () => assert.ok(readme.includes('stored only if no earlier prediction is still waiting to be checked')));
    it('README', () => assert.ok(readme.includes('each time the single pending prediction matures')));
});

describe('the version is stated consistently', () => {
    // Compares the places that must agree with each other, so a version bump never needs this test edited.
    const claude = read('CLAUDE.md');
    const versions = {
        pageMeta: html.match(/<meta name="app-version" content="v(\d+\.\d+)">/)?.[1],
        claude: claude.match(/Current Model Parameters \(v(\d+\.\d+)\)/)?.[1],
        appendixCurrent: appendix.match(/\*\*Current version:\*\* v(\d+\.\d+)/)?.[1],
        appendixFooter: appendix.match(/Generated by Potomac Pulse v(\d+\.\d+)/)?.[1],
        readme: readme.match(/\*\*Current Version\*\*: v(\d+\.\d+)/)?.[1],
        todo: read('TODO.md').match(/current version: v(\d+\.\d+)/)?.[1]
    };
    it('every place states a version', () => {
        for (const [k, v] of Object.entries(versions)) assert.ok(v, `${k} has no version`);
    });
    it('index.html app-version meta, CLAUDE.md, the appendix and the README agree', () => {
        assert.equal(new Set(Object.values(versions)).size, 1, JSON.stringify(versions));
    });
    it('the changelog has a row for that version', () => {
        assert.match(read('src/assets/CHANGELOG.md'), new RegExp(`\\| v${versions.pageMeta.replace('.', '\\.')} \\|`));
    });
});
